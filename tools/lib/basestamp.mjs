// Stamps for the gate's base worlds ('G6B Seed Base', 'G6B Flat Base', 'G6B Seed <seed>'). A run dir is reused between runs, so a
// base world made by an older creation path (data packs recorded, allowCommands 0, an older Minecraft) survived and generated
// different terrain than the golden (PT: magma and bubble columns where the golden has water, moving S1's pinned survey sha).
// Each base world now carries `architect-base-stamp.json` with a hash of its creation recipe; a missing stamp (every world made
// before this existed) or a different hash means stale: the world is moved aside (never deleted) and the driver makes it again.
// No client needed here: tools/lib/run6b.mjs does the opening, this file only decides and writes the stamp.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

export const STAMP_FILE = 'architect-base-stamp.json';
/** Bump when the creation path changes (the open options, the rules, the spawn teleport) so every run dir rebuilds its bases. */
export const BASE_RECIPE_VERSION = 2;

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');

/** The Minecraft version the checkout builds against (a world generated by another version differs). */
export function minecraftVersion(root = ROOT) {
  try { return /^minecraft_version=(.+)$/m.exec(fs.readFileSync(path.join(root, 'mod', 'gradle.properties'), 'utf8'))?.[1].trim() ?? 'unknown'; } catch { return 'unknown'; }
}

/**
 * (housekeeping 3) The host a driver's world opens on: 'server' when the runner gave it the headless server's launch script
 * (tools/lib/hosts.mjs: GATE6B_CLIENT_SCRIPT / GATE6A_CLIENT_SCRIPT = tools/run-headless-server.mjs), else 'client'.
 */
export function gateHost(env = process.env) {
  return /headless/.test(`${env.GATE6B_CLIENT_SCRIPT ?? ''} ${env.GATE6A_CLIENT_SCRIPT ?? ''}`) ? 'server' : 'client';
}

/**
 * What creates a base world: the open options and rules the drivers' base steps use (mode creative, cheats, spawn tp), and the host
 * (housekeeping 3): a base the headless server made records its data packs and allowCommands 0 in level.dat, and a client reusing it
 * in the same run dir read S1's pinned survey as 572271bd (magma and bubble columns) instead of the golden's 3e5bd5b7 (w-ingame item
 * 7, failing "on both hosts" after a headless run had made the base), so a base made by the other host is stale.
 */
export function baseRecipe({ preset, seed }, { minecraft = minecraftVersion(), host = gateHost() } = {}) {
  return { v: BASE_RECIPE_VERSION, minecraft, host, mode: 'creative', cheats: true, preset, seed: String(seed), rules: preset === 'flat' ? 'exact' : 'default', spawn: [0.5, 200, 0.5] };
}
export const recipeHash = (recipe) => crypto.createHash('sha256').update(JSON.stringify(recipe)).digest('hex').slice(0, 16);

export function readStamp(saves, name) {
  try { return JSON.parse(fs.readFileSync(path.join(saves, name, STAMP_FILE), 'utf8')); } catch { return null; }
}
export function writeStamp(saves, name, recipe, now = new Date()) {
  fs.writeFileSync(path.join(saves, name, STAMP_FILE), `${JSON.stringify({ hash: recipeHash(recipe), recipe, createdAt: now.toISOString() }, null, 2)}\n`);
}

/** 'missing' (no world), 'unstamped' (made before stamps), 'stale' (another recipe) or 'current'. */
export function baseStatus(saves, name, recipe) {
  if (!fs.existsSync(path.join(saves, name, 'level.dat'))) return 'missing';
  const s = readStamp(saves, name);
  if (!s?.hash) return 'unstamped';
  return s.hash === recipeHash(recipe) ? 'current' : 'stale';
}

/** Moves a stale world to <saves>/../saves-stale/<name>-<timestamp> (kept for inspection; nothing is deleted). Returns the new path. */
export function quarantineBase(saves, name, now = new Date()) {
  const src = path.join(saves, name);
  if (!src.startsWith(saves + path.sep) || !name.startsWith('G6B ')) throw new Error(`refusing to move ${src}`);
  const dstDir = path.join(path.dirname(saves), 'saves-stale');
  fs.mkdirSync(dstDir, { recursive: true });
  const base = path.join(dstDir, `${name}-${now.toISOString().replace(/[:.]/g, '-')}`);
  let dst = base;
  for (let i = 2; fs.existsSync(dst); i++) dst = `${base}-${i}`;
  fs.renameSync(src, dst);
  return dst;
}

/**
 * True when `name` exists with the current recipe. A stale or unstamped world is moved aside and false is returned, so the
 * caller's "make it if missing" path rebuilds it; a missing world also returns false.
 */
export function baseCurrent(saves, name, spec, { log = () => {}, ...opts } = {}) {
  const recipe = baseRecipe(spec, opts);
  const st = baseStatus(saves, name, recipe);
  if (st === 'current') return true;
  if (st !== 'missing') log(`base world "${name}" is ${st} (recipe ${recipeHash(recipe)}): moved to ${quarantineBase(saves, name)}; it will be rebuilt`);
  return false;
}
