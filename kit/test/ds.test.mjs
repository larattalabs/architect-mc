// 7b DS (docs/CONTRACT.md "Phase 7b" §3 row 7): the designer's site inputs in the kit. lib/siteBrief.mjs puts a site into words (the
// affordances AF finds, in the design frame; the fit's row; the ports and keep cells) and renders the empty site four ways;
// tools/site-brief.mjs writes site.json and the renders for the sidecar's scratch dir. The words of the six 7bF fixtures are a
// committed golden (kit/test/fixtures/ds/brief-sections.json; UPDATE_GOLDEN=1 rewrites it), the renders are deterministic, and
// DS's two extra cliffs (tools/ds-fixtures.mjs) are what the site-variant gate needs: the cliff house re-runs clean on cliff_east and
// writes a player's cells on cliff_owned (site_keep).
import test from 'node:test';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { Site } from '../lib/site.mjs';
import { siteFixture } from '../lib/siteFixture.mjs';
import { affordanceWords, designBox, openSide, renderEmptySite, siteAnalysis, siteJson, siteSection, SITE_RENDERS, SITE_WORDS_MAX } from '../lib/siteBrief.mjs';
import { buildDsFixtures } from '../tools/ds-fixtures.mjs';
import { FIT_IDS } from '../lib/siteFits.mjs';

const KIT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FIXTURES = ['cliff_face', 'tunnel_hill', 'rift_site', 'grove', 'overhang', 'trunk'];
const GOLDEN = path.join(KIT, 'test', 'fixtures', 'ds', 'brief-sections.json');
const dsSite = (id) => {
  const dir = path.join(KIT, 'test', 'fixtures', 'ds', id);
  return new Site(fs.readFileSync(path.join(dir, 'volume.bin')), JSON.parse(fs.readFileSync(path.join(dir, 'site.json'), 'utf8')));
};

test('the Site section of the six fixtures: deterministic, in the design frame, one per fit (golden)', () => {
  const out = {};
  for (const id of FIXTURES) {
    const site = siteFixture(id);
    const a = siteSection(site, { renders: Object.values(SITE_RENDERS).map((f) => `site/${f}`) });
    assert.deepEqual(siteSection(site, { renders: Object.values(SITE_RENDERS).map((f) => `site/${f}`) }), a, `${id}: deterministic`);
    assert.match(a[0], /^## Site \(binding/);
    assert.ok(a.some((l) => l.includes(`**Fit: \`${site.fit}\`**`)), `${id}: names its fit`);
    assert.ok(a.some((l) => l.includes(`exactly the lot box, ${site.size.x} x ${site.size.y} x ${site.size.z}`)), `${id}: the lot's size`);
    for (const p of site.ports) assert.ok(a.some((l) => l.includes(`\`${p.name}\` (${p.kind}) at ${p.at.join(', ')}`)), `${id}: port ${p.name}`);
    out[id] = a;
  }
  // every fit is put into words
  assert.deepEqual([...new Set(FIXTURES.map((id) => siteFixture(id).fit))].sort(), [...FIT_IDS].sort());
  if (process.env.UPDATE_GOLDEN) fs.writeFileSync(GOLDEN, `${JSON.stringify({ comment: 'GENERATED by kit/test/ds.test.mjs (UPDATE_GOLDEN=1): the BRIEF Site section of each 7bF fixture', sections: out }, null, 1)}\n`);
  assert.deepEqual(JSON.parse(fs.readFileSync(GOLDEN, 'utf8')).sections, out);
});

test('the words say what AF finds, in the design frame: the cliff, the trunk, the gap, the overhang, the keep cells', () => {
  const words = (id) => siteSection(siteFixture(id)).join('\n');
  assert.match(words('cliff_face'), /a cliff face facing south \(\+z, your front\), 22 tall and 32 long/);
  assert.match(words('trunk'), /a tree trunk 30 tall/);
  assert.match(words('trunk'), /Keep: 260 keep-critical cells \(`site.keepCritical`, the trunk's logs\)/);
  assert.match(words('rift_site'), /a gap 9 wide between two faces/);
  assert.match(words('rift_site'), /at least 2 walk or door ports/);
  assert.match(words('overhang'), /an overhang of \d+ cells/);
  assert.match(words('overhang'), /Keep: 4 keep-critical cells \(`site.keepCritical`, the hang points\)/);
  assert.match(words('grove'), /\*\*Fit: `on_pad`\*\*/);
  // at most SITE_WORDS_MAX affordances, at most 2 pads on a non-pad site
  for (const id of FIXTURES) {
    const site = siteFixture(id);
    const { near } = siteAnalysis(site);
    assert.ok(near.length <= SITE_WORDS_MAX);
    if (site.fit !== 'on_pad') assert.ok(near.filter((a) => a.kind === 'pad').length <= 2, id);
  }
});

test('a design box is the world box turned into the design frame (a quarter-turned site swaps x and z)', () => {
  const site = siteFixture('cliff_face');
  const L = site.lot;
  assert.deepEqual(designBox(site, L), { minX: 0, maxX: site.size.x - 1, minY: 0, maxY: site.size.y - 1, minZ: 0, maxZ: site.size.z - 1 });
  const spec = structuredClone(siteFixture('cliff_face').spec);
  spec.frame.rotation = 'clockwise_90';
  const turned = new Site(fs.readFileSync(path.join(KIT, 'test', 'fixtures', 'site', 'cliff_face', 'volume.bin')), spec);
  const b = designBox(turned, { minX: L.minX, minY: L.minY, minZ: L.minZ, maxX: L.maxX, maxY: L.maxY, maxZ: L.maxZ });
  assert.equal(b.maxX - b.minX + 1, turned.size.x);
  assert.equal(b.maxZ - b.minZ + 1, turned.size.z);
  // clockwise_90 turns the design's south to the world's west and its east to the world's south (AF's frame table): the world's
  // south-facing cliff faces east in this design frame
  assert.equal(turned.worldFacing('east'), 'south');
  const face = siteAnalysis(turned).near.find((a) => a.kind === 'cliff_face');
  assert.match(affordanceWords(turned, face), /facing east \(\+x\)/);
});

test('site.json carries the lot, the spec Site reads, the fit row, the ports, the keep cells and the analysis', () => {
  const site = siteFixture('overhang');
  const j = siteJson(site);
  assert.deepEqual(j.lot, site.lot);
  assert.equal(j.fit, 'suspend');
  assert.equal(j.fitRow.bears, 'up');
  assert.equal(j.keepCritical.length, 4);
  assert.ok(j.affordances.some((a) => a.kind === 'overhang'));
  // the kit's own Site reads it back (the wrapper form), as the build's --lot does
  const back = new Site(fs.readFileSync(path.join(KIT, 'test', 'fixtures', 'site', 'overhang', 'volume.bin')), JSON.parse(JSON.stringify(j)));
  assert.deepEqual(back.size, site.size);
});

test('the four empty-site renders: PNGs, deterministic; the open side faces the air', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ds-renders-'));
  try {
    for (const id of ['cliff_face', 'trunk']) {
      const site = siteFixture(id);
      const a = renderEmptySite(site, path.join(dir, `${id}-a`));
      const b = renderEmptySite(site, path.join(dir, `${id}-b`));
      assert.deepEqual(a, Object.values(SITE_RENDERS));
      for (const f of a) {
        const x = fs.readFileSync(path.join(dir, `${id}-a`, f));
        assert.deepEqual(x.subarray(0, 8), Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]), `${id} ${f}: a PNG`);
        const h = (buf) => crypto.createHash('sha256').update(buf).digest('hex');
        assert.equal(h(x), h(fs.readFileSync(path.join(dir, `${id}-b`, f))), `${id} ${f}: deterministic`);
      }
    }
    assert.equal(openSide(siteFixture('cliff_face')), 'south');
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

test('tools/site-brief.mjs writes site.json and the renders and prints the section; a bad site exits 1, bad usage 2', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ds-tool-'));
  try {
    const fx = path.join(KIT, 'test', 'fixtures', 'site', 'rift_site');
    const r = spawnSync(process.execPath, [path.join(KIT, 'tools', 'site-brief.mjs'), path.join(fx, 'volume.bin'), path.join(fx, 'site.json'), '--out', dir], { encoding: 'utf8' });
    assert.equal(r.status, 0, r.stderr);
    const j = JSON.parse(r.stdout.trim().split('\n').pop());
    assert.equal(j.ok, true);
    assert.deepEqual(j.renders, Object.values(SITE_RENDERS).map((f) => `site/${f}`));
    assert.deepEqual(j.section, siteSection(siteFixture('rift_site'), { renders: j.renders }));
    for (const f of ['site.json', ...Object.values(SITE_RENDERS)]) assert.ok(fs.existsSync(path.join(dir, f)), f);
    const off = spawnSync(process.execPath, [path.join(KIT, 'tools', 'site-brief.mjs'), path.join(fx, 'volume.bin'), path.join(fx, 'site.json'), '--out', path.join(dir, 'n'), '--no-renders'], { encoding: 'utf8' });
    assert.equal(JSON.parse(off.stdout.trim().split('\n').pop()).renders.length, 0);
    assert.ok(!fs.existsSync(path.join(dir, 'n', 'site-iso.png')));
    // another volume than the spec's
    const bad = spawnSync(process.execPath, [path.join(KIT, 'tools', 'site-brief.mjs'), path.join(KIT, 'test', 'fixtures', 'site', 'grove', 'volume.bin'), path.join(fx, 'site.json'), '--out', dir], { encoding: 'utf8' });
    assert.equal(bad.status, 1);
    assert.match(JSON.parse(bad.stdout.trim()).error, /another volume/);
    assert.equal(spawnSync(process.execPath, [path.join(KIT, 'tools', 'site-brief.mjs'), path.join(fx, 'volume.bin')], { encoding: 'utf8' }).status, 2);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

test("DS's fixtures: regenerated byte for byte; the cliff house re-runs clean on cliff_east and writes a player's cells on cliff_owned", () => {
  for (const fx of buildDsFixtures()) {
    assert.ok(Buffer.from(fx.volume).equals(fs.readFileSync(path.join(fx.dir, 'volume.bin'))), `${fx.id}: volume.bin`);
    assert.equal(fs.readFileSync(path.join(fx.dir, 'site.json'), 'utf8'), `${JSON.stringify(fx.site, null, 1)}\n`, `${fx.id}: site.json`);
  }
  const out = fs.mkdtempSync(path.join(os.tmpdir(), 'ds-cliffs-'));
  try {
    const build = (id) => {
      const dir = path.join(KIT, 'test', 'fixtures', 'ds', id);
      const r = spawnSync(process.execPath, [path.join(KIT, 'build.mjs'), 'fit_attach_to_cliff', '--out', path.join(out, id), '--site', path.join(dir, 'volume.bin'), '--lot', path.join(dir, 'site.json'), '--json'], { encoding: 'utf8' });
      return { code: r.status, j: JSON.parse(r.stdout.trim().split('\n').pop()) };
    };
    const east = build('cliff_east');
    assert.equal(east.code, 0, JSON.stringify(east.j.errors));
    assert.equal(east.j.site.ok, true);
    assert.deepEqual(east.j.sidecar ? JSON.parse(fs.readFileSync(east.j.sidecar, 'utf8')).size : null, { x: 18, y: 24, z: 12 });
    const owned = build('cliff_owned');
    assert.equal(owned.code, 1);
    assert.equal(owned.j.site.findings[0].rule, 'site_keep');
    assert.deepEqual(dsSite('cliff_owned').size, { x: 16, y: 22, z: 12 });
  } finally {
    fs.rmSync(out, { recursive: true, force: true });
  }
});
