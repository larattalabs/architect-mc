#!/usr/bin/env node
// Slice 0b gate item 2 (the fit half): for every kit example with a massing, the mirrored copy's and the mirrored massing's
// lot-fitting inputs (size, front, entrance, groundY, approach length), written to kit/test/fixtures/mirror-fit.json for the
// mod's MirrorFitTest (LotFitting.fit on both: same rotation, origin within +-2 in x and z, equal y).
//   node kit/tools/mirror-fit-fixture.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { importDesign, listDesigns, loadDesign } from '../build.mjs';
import { mirrorAxisOf, mirrorSidecar } from '../lib/mirror.mjs';
import { builtinBible } from '../lib/bible.mjs';
import { chooseRecipe, seedOf } from '../lib/variation.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const KIT = path.dirname(HERE);
const fit = (sc) => {
  const e = sc.anchors?.entrance;
  return { size: [sc.size.x, sc.size.y, sc.size.z], front: sc.front, entrance: e ? [e.x, e.z] : null, groundY: sc.groundY, approach: sc.approach?.length && e ? sc.approach.length : 0 };
};
const out = [];
for (const id of listDesigns()) {
  const m = path.join(KIT, 'massings', `${id}_massing`, `${id}_massing.blueprint.json`);
  if (!fs.existsSync(m)) continue;
  const massing = JSON.parse(fs.readFileSync(m, 'utf8'));
  // the archetype (unmirrored), and its first copy as the copy stage builds it (ordinal 1: mirrored, with its shift and param)
  const mod = await importDesign(id);
  const bible = builtinBible('rustic');
  const values = Object.fromEntries(Object.entries(mod.params ?? {}).map(([k, p]) => [k, p.default]));
  const load = (roles, v, mirror) => loadDesign(id, { palette: { bible: { id: 'rustic', version: 1, roles } }, values: v, mirror });
  const r = await chooseRecipe({ load, bible, params: mod.params ?? {}, values, seed: seedOf('g_fit', id), ordinal: 1, massing });
  for (const [label, roles, v, mirror] of [['archetype', bible.roles, values, false], ['copy #2', r.roles, r.values, r.mirror]]) {
    const bp = await load(roles, v, mirror);
    const detail = JSON.parse(JSON.stringify(bp.sidecar()));
    const ms = mirror ? mirrorSidecar(massing, mirrorAxisOf(detail.front)) : massing;
    out.push({ id, label, mirror, recipe: label === 'copy #2' ? { shift: r.shift?.name ?? null, param: r.param, mirror: r.mirror } : null, detail: fit(detail), massing: fit(ms) });
  }
}
fs.writeFileSync(path.join(KIT, 'test', 'fixtures', 'mirror-fit.json'), `${JSON.stringify({ comment: 'GENERATED by kit/tools/mirror-fit-fixture.mjs', pairs: out }, null, 1)}\n`);
console.log(`${out.length} pairs`);
