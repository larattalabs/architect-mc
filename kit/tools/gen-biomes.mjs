#!/usr/bin/env node
// node kit/tools/gen-biomes.mjs [--server-jar <jar>] [--work <dir>]
//
// (6c H §1.3) Generates kit/lib/fluids/biomes.mjs from vanilla 26.3's built-in data pack (data/minecraft/worldgen/biome/*.json): each
// biome's base temperature and temperature modifier, so `freezesAt(biome, y)` answers 26.3's Biome.shouldFreeze temperature rule at a
// surface y (the light and the sky are the realise's: a body's ice cap is written, never waited for). The jar is never copied into the
// repo (mcjar.mjs finds it in the Loom cache).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { MC_VERSION, findJar, openZip, parseArgs, workDir } from './mcjar.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.resolve(HERE, '../lib/fluids/biomes.mjs');

const o = parseArgs(process.argv.slice(2));
const work = workDir(o.work);
const jar = await findJar('server', o['server-jar'], work);
let zip = openZip(jar);
// the bundled server jar holds the real one under META-INF/versions
const inner = zip.names().find((n) => /^META-INF\/versions\/.*\.jar$/.test(n));
if (inner) {
  const f = path.join(work, 'server-inner.jar');
  fs.writeFileSync(f, zip.read(inner));
  zip = openZip(f);
}
const pre = 'data/minecraft/worldgen/biome/';
const rows = [];
for (const n of zip.names().filter((x) => x.startsWith(pre) && x.endsWith('.json')).sort()) {
  const b = JSON.parse(zip.read(n).toString('utf8'));
  rows.push([`minecraft:${n.slice(pre.length, -5)}`, b.temperature, b.temperature_modifier ?? 'none']);
}
const lines = rows.map(([id, t, m]) => `  '${id}': [${t}, '${m}'],`);
const src = `// GENERATED by kit/tools/gen-biomes.mjs from vanilla ${MC_VERSION}'s data pack (worldgen/biome). Do not edit by hand.
//
// (6c H §1.3) Which biomes freeze open water at a surface y: 26.3's Biome.shouldFreeze needs the height-adjusted temperature under 0.15
// (coldEnoughToSnow's rule: over sea level + 17 the temperature falls 0.05 per 40 blocks, with a noise of at most 8 blocks either way;
// the frozen modifier, frozen oceans', only ever lowers it towards freezing). A body whose surface is sky-lit there is capped with ice
// (H-a's ice caps); \`freezesAt\` answers the cold side of the noise, so a borderline column is capped (an ice cap never melts by
// temperature, only by light: M17).

/** Biome id -> [base temperature, temperature modifier]. */
export const BIOMES = Object.freeze({
${lines.join('\n')}
});

/** 26.3's sea level and the height over it where the temperature starts to fall, and the noise's reach in blocks. */
export const SEA_LEVEL = 63, LAPSE_FROM = SEA_LEVEL + 17, LAPSE_NOISE = 8;

/** Whether open water at surface \`y\` freezes in \`biome\` (an id; \`minecraft:\` implied); an unknown biome never does. */
export function freezesAt(biome, y) {
  const id = String(biome ?? '').includes(':') ? String(biome) : \`minecraft:\${biome}\`;
  const b = BIOMES[id];
  if (!b) return false;
  const [t, mod] = b;
  if (t < 0.15 || mod === 'frozen') return true;
  if (y <= LAPSE_FROM - LAPSE_NOISE) return false;
  return t - ((y - LAPSE_FROM + LAPSE_NOISE) * 0.05) / 40 < 0.15;
}
`;
fs.writeFileSync(OUT, src);
console.error(`wrote ${path.relative(process.cwd(), OUT)} (${rows.length} biomes)`);
