#!/usr/bin/env node
// (RTE4) Writes kit/test/fixtures/rte-compat/corpus.json.gz: the RTE readers' compatibility corpus. Each released kit (v0.85.0..v0.88.0,
// in detached worktrees of those tags) plans and grows the cases of kit/tools/rte-compat-worker.mjs (every district id set the RTE slices
// met: b/b_1, b/b_1/b_1_g1, b/b_street, a lone b_street, b_street + c, quay/quayside/quay_1, ids ending _g<n>; V districts on flat land and
// following districts on a shore, one to three growth rounds), each IR and revision IR exactly as that release wrote it (route tags and
// its numbering included; an IR two releases wrote alike is kept once, under the first). Then v0.88.0's readers read every case's rounds
// (`expected`: what kit/test/rte-compat.test.mjs requires of this tree, and DistrictLandCompatTest of the mod's land), and each release's
// own readers its own cases (`own`, for the record: RTE2 and RTE3 changed some readings on purpose).
//   node kit/tools/rte-compat-fixture.mjs v0.85.0=<tree> v0.86.0=<tree> v0.87.0=<tree> v0.88.0=<tree>
// The trees are worktrees at those tags (`git worktree add --detach ../architect-mc-rte-v088 v0.88.0`); v0.88.0's must be given.
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import os from 'node:os';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const FIXTURE = path.join(HERE, '..', 'test', 'fixtures', 'rte-compat', 'corpus.json.gz');
export const EXPECTED_FROM = 'v0.88.0';

/** The corpus: {versions, expectedFrom, cases: [{key, version, id, recipe, seed, districts, grows, log, ir, revisions, expected, own}]}. */
export function loadCorpus(file = FIXTURE) {
  return JSON.parse(zlib.gunzipSync(fs.readFileSync(file)).toString('utf8'));
}

function run(args) {
  const r = spawnSync(process.execPath, [path.join(HERE, 'rte-compat-worker.mjs'), ...args], { encoding: 'utf8', maxBuffer: 1 << 30 });
  if (r.status !== 0) throw new Error(`worker ${args[0]} ${args[1]}: exit ${r.status}: ${r.stderr.slice(-2000)}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const trees = Object.fromEntries(process.argv.slice(2).map((a) => a.split('=')).map(([v, t]) => [v, path.resolve(t)]));
  if (!trees[EXPECTED_FROM]) throw new Error(`usage: node kit/tools/rte-compat-fixture.mjs v0.85.0=<tree> ... ${EXPECTED_FROM}=<tree>`);
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'rte-compat-'));
  const versions = Object.keys(trees).sort((a, b) => a.localeCompare(b, 'en', { numeric: true }));
  const cases = [], seen = new Map();
  for (const v of versions) {
    const f = path.join(tmp, `plan-${v}.json`);
    run(['plan', trees[v], f]);
    for (const c of JSON.parse(fs.readFileSync(f, 'utf8'))) {
      if (c.error) { console.log(`${v} ${c.id}: not planned (${c.error})`); continue; }
      const body = JSON.stringify({ ir: c.ir, revisions: c.revisions });
      if (seen.has(body)) { seen.get(body).alsoBy.push(v); continue; }
      const k = { key: `${v}/${c.id}`, version: v, alsoBy: [], ...c };
      seen.set(body, k);
      cases.push(k);
    }
  }
  const all = path.join(tmp, 'cases.json');
  fs.writeFileSync(all, JSON.stringify(cases));
  run(['read', trees[EXPECTED_FROM], all, path.join(tmp, 'expected.json')]);
  const expected = JSON.parse(fs.readFileSync(path.join(tmp, 'expected.json'), 'utf8'));
  cases.forEach((c, i) => { c.expected = expected[i]; });
  for (const v of versions) {
    if (v === EXPECTED_FROM) { cases.forEach((c) => { if (c.version === v) c.own = null; }); continue; }
    const mine = cases.filter((c) => c.version === v);
    const f = path.join(tmp, `mine-${v}.json`);
    fs.writeFileSync(f, JSON.stringify(mine));
    run(['read', trees[v], f, path.join(tmp, `own-${v}.json`)]);
    const own = JSON.parse(fs.readFileSync(path.join(tmp, `own-${v}.json`), 'utf8'));
    mine.forEach((c, i) => { c.own = JSON.stringify(own[i]) === JSON.stringify(c.expected) ? null : own[i]; });
  }
  const out = { $comment: 'Generated by kit/tools/rte-compat-fixture.mjs from the released trees; read by kit/test/rte-compat.test.mjs and mod DistrictLandCompatTest. Do not edit. own: null when the release read its case as expected.', versions, expectedFrom: EXPECTED_FROM, cases };
  fs.mkdirSync(path.dirname(FIXTURE), { recursive: true });
  fs.writeFileSync(FIXTURE, zlib.gzipSync(Buffer.from(JSON.stringify(out)), { level: 9 }));
  fs.rmSync(tmp, { recursive: true, force: true });
  const rounds = cases.reduce((a, c) => a + 1 + c.revisions.length, 0);
  console.log(`wrote ${FIXTURE}: ${cases.length} cases (${rounds} effective IRs) from ${versions.join(', ')}; ${fs.statSync(FIXTURE).size} bytes`);
}
