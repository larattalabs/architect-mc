#!/usr/bin/env node
// (RTE4) Writes kit/test/fixtures/rte4/land-irs.json: districts `b` and `b_street` planned by the bundled districts program, where b's street
// roads `b_street_w`, `b_street_e` read by id as district b_street's; the districts pass records each district's roads (ext
// architect_mc:district {id}). For the mod's DistrictLandRte4Test and kit/test/rte4.test.mjs (which checks the file is current); both read
// the untagged and malformed variants by editing this IR's tags in memory.
//   node kit/tools/rte4-fixture.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { planRegion } from '../lib/region/plan.mjs';
import { makeColumns } from '../lib/region/pack.mjs';

const KIT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
export const FIXTURE = path.join(KIT, 'test', 'fixtures', 'rte4', 'land-irs.json');

/** The b / b_street plan (160 x 160, flat at 64; v0.87.0's release review's case). */
export async function planBStreet() {
  const W = 160, c = makeColumns(0, 0, W, W, 1);
  c.ground.fill(64); c.height.fill(64); c.floor.fill(62); c.flags.fill(0);
  const districts = [{ id: 'b', size: [40, 40], lots: 1, shared: 'square' }, { id: 'b_street', size: [40, 40], lots: 1, shared: 'square' }];
  return planRegion({ programFile: path.join(KIT, 'regions', 'districts.mjs'), survey: c, claim: { minX: 0, minZ: 0, maxX: W - 1, maxZ: W - 1, minY: -64, maxY: 319 }, params: { spec: { districts } }, seed: '7' });
}

export async function makeIrs() {
  const p = await planBStreet();
  // (the members architect_mc:land reads)
  const { params, parts, lots, roads, paths, graph } = p.ir;
  return { $comment: 'Generated by kit/tools/rte4-fixture.mjs; read by mod DistrictLandRte4Test and kit/test/rte4.test.mjs. Do not edit.', bStreet: { params, parts, lots, roads, paths, graph } };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = `${JSON.stringify(await makeIrs(), null, 1)}\n`;
  if (process.argv.includes('--check')) {
    const ok = fs.existsSync(FIXTURE) && fs.readFileSync(FIXTURE, 'utf8') === text;
    console.log(ok ? 'current' : 'stale');
    process.exit(ok ? 0 : 1);
  }
  fs.mkdirSync(path.dirname(FIXTURE), { recursive: true });
  fs.writeFileSync(FIXTURE, text);
  console.log(`wrote ${FIXTURE}`);
}
