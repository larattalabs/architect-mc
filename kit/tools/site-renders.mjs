#!/usr/bin/env node
// (7b SV) The sha goldens of the six fit examples' composite and section renders (kit/test/fixtures/sv-renders.json), which
// kit/test/sv.test.mjs holds the renderer to (CI reproduces them on Linux).
//   node kit/tools/site-renders.mjs [--out <dir>]   rewrite the goldens (and keep the PNGs in <dir>, default a temp dir)
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { renderStructure } from '../render.mjs';
import { Site } from '../lib/site.mjs';
import { importDesign, SITE_DESIGNS } from '../build.mjs';
import { listSiteDesigns } from './examples.mjs';

const KIT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const i = process.argv.indexOf('--out');
const out = i > 0 ? path.resolve(process.argv[i + 1]) : fs.mkdtempSync(path.join(os.tmpdir(), 'site-renders-'));
const renders = {};
for (const id of listSiteDesigns().sort()) {
  const mod = await importDesign(id, SITE_DESIGNS);
  const r = renderStructure(path.join(KIT, 'examples', id, `${id}.nbt`), { out, site: Site.fixture(mod.exampleSite), views: ['composite', 'section'] });
  for (const v of ['composite', 'section']) renders[`${id}.${v}`] = crypto.createHash('sha256').update(fs.readFileSync(r.files[v])).digest('hex');
}
const sorted = Object.fromEntries(Object.entries(renders).sort(([a], [b]) => (a < b ? -1 : 1)));
fs.writeFileSync(path.join(KIT, 'test', 'fixtures', 'sv-renders.json'), `${JSON.stringify({ comment: 'GENERATED by kit/tools/site-renders.mjs: sha256 of the PNG bytes', renders: sorted }, null, 1)}\n`);
console.log(`${Object.keys(sorted).length} renders; PNGs in ${out}`);
