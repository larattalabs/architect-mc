#!/usr/bin/env node
// node kit/tools/gen-vocab.mjs [--check] [--no-jar] [--reuse] [--work <dir>] [--server-jar <jar>] [--java <bin>] [--report <file>]
//
// (6c VOC) The block vocabulary (docs/CONTRACT.md "Phase 6c slice VOC" §1-§3): one generator writes every derived file from the
// same data, as tools/gen-equivalents.mjs does:
//   kit/vocab/edges.json                 the derived per-block edges (family links, the tier path's raw items, one survival source,
//                                        and BlockDump/VocabDump's rt, wx, be, ff): never a recipe or a loot table (N-VOC-7)
//   kit/lib/blocks.mjs                   its vocabulary section (`fam`, `col`, `t`, `sv`, `rt`, `wx`, `be`, `ft`, `ff`)
//   kit/lib/vocab/survival.mjs           CREATIVE_ONLY, COSTS and (6c RS) FREE_EXCEPT (check.mjs and connectors/bom.mjs import them)
//   kit/lib/region/survivalData.mjs      (6c RS) the region evaluator's copy: FREE_NATURAL, CREATIVE_ONLY, COSTS (the realise lint)
//   mod/.../architect_mc/survival_items.json  creativeOnly and costs (SurvivalItems.java reads it)
//   kit/schemas/vocab-1.json             the vocab/1 document (the systemRef `vocab/1`, and `#compact`)
//
// With the jar (the Loom cache, --server-jar, or the work dir; never downloaded here) it runs the 26.3 data report, BlockDump.java and
// VocabDump.java (gen-blocks.mjs's collect), reads the jar's built-in data pack (kit/tools/vocab-scan.mjs) and derives the edges, then
// everything else from them (kit/tools/vocab-derive.mjs). With --no-jar (or no jar on the machine) it derives everything from the
// committed edges.json instead: the same function, so the same bytes. --check writes nothing and exits 1 when a file on disk differs
// (the drift test, kit/test/vocab.test.mjs, runs `--check --no-jar`; the gate's voc-unit runs it with the jar).
// Changing tiers.json's stops or tag rows, modifiers.json or survival.json's obtain rows needs the jar run (they shape the edges).
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..', '..');
export const OUT = {
  edges: path.join(ROOT, 'kit', 'vocab', 'edges.json'),
  blocks: path.join(ROOT, 'kit', 'lib', 'blocks.mjs'),
  survival: path.join(ROOT, 'kit', 'lib', 'vocab', 'survival.mjs'),
  survivalRegion: path.join(ROOT, 'kit', 'lib', 'region', 'survivalData.mjs'),
  survivalItems: path.join(ROOT, 'mod', 'src', 'main', 'resources', 'data', 'architect_mc', 'survival_items.json'),
  doc: path.join(ROOT, 'kit', 'schemas', 'vocab-1.json'),
};
const TABLES = ['tiers', 'roles', 'survival', 'hazards', 'modifiers'];
const MARK = '/*@@VOCAB@@*/';
const SECTION = /^\/\/ \d+ blocks' vocabulary \(generated by kit\/tools\/gen-vocab\.mjs[^\n]*\n(?:v\('[^\n]*\n?)*/m;

/** blocks.mjs text with its vocabulary section replaced by the template's marker. */
export function stripVocab(text) {
  return SECTION.test(text) ? text.replace(SECTION, `${MARK}\n`) : text;
}
/** gen-blocks.mjs: a freshly generated blocks.mjs (marker in place) given the vocabulary section of the file it replaces. */
export function carryVocab(fresh, old) {
  const m = SECTION.exec(old);
  return m ? fresh.replace(`${MARK}\n`, () => m[0].endsWith('\n') ? m[0] : `${m[0]}\n`) : fresh;
}

export function readTables() {
  return Object.fromEntries(TABLES.map((t) => [t, JSON.parse(fs.readFileSync(path.join(ROOT, 'kit', 'vocab', `${t}.json`), 'utf8'))]));
}

/** Checks every row of every table carries a `why` (and every override its evidence): gate item 1. Returns the problems. */
export function tableProblems(tables) {
  const out = [];
  const need = (t, rows, extra = []) => rows.forEach((r, i) => {
    if (typeof r.why !== 'string' || !r.why.trim()) out.push(`${t}[${i}]: no why`);
    for (const k of extra) if (typeof r[k] !== 'string' || !r[k].trim()) out.push(`${t}[${i}]: no ${k}`);
  });
  need('tiers.rows', tables.tiers.rows);
  need('roles.rows', tables.roles.rows);
  need('roles.every', [tables.roles.every]);
  need('survival.costs', tables.survival.costs);
  need('survival.classes', tables.survival.classes, ['evidence']);
  need('survival.obtain', tables.survival.obtain, ['evidence']);
  need('survival.mod', tables.survival.mod, ['evidence']);
  need('hazards.rows', tables.hazards.rows);
  need('modifiers.rows', tables.modifiers.rows);
  return out;
}

/** edges.json text: a header, then one line per block (diffs stay readable). */
export function edgesText(e) {
  const head = { format: 1, note: e.note, mc: e.mc, generator: e.generator, digests: e.digests, tagRows: e.tagRows };
  const h = JSON.stringify(head, null, 1).replace(/\n}$/, '');
  const rows = Object.keys(e.blocks).sort((a, b) => (a < b ? -1 : a > b ? 1 : 0)).map((k) => ` ${JSON.stringify(k)}: ${JSON.stringify(e.blocks[k])}`);
  return `${h},\n "blocks": {\n${rows.join(',\n')}\n }\n}\n`;
}

const EDGES_NOTE = 'GENERATED by kit/tools/gen-vocab.mjs from the 26.3 server jar (docs/CONTRACT.md "Phase 6c slice VOC" §3, N-VOC-7): only the derived edges per block (j: family links; ck: the cooking inputs, smelting joining no family; raw, rp: the raw items and recipe of the cheapest recipe path; sv, src: the generated survival class and one source; rt, wx, be, ff: the dumps\' facts), and the item-tag members tiers.json\'s tag rows need. Never a recipe or a loot table. Do not edit: regenerate with the jar.';

/** The jar half: the dumps and the data pack, then the edges. */
async function fromJar(o, tables) {
  const { collect } = await import('./gen-blocks.mjs');
  const { MC_VERSION, findJava, openZip } = await import('./mcjar.mjs');
  const S = await import('./vocab-scan.mjs');
  const { report, dump, tags, work } = await collect(o);
  const serverClasses = path.join(work, 'versions', MC_VERSION, `server-${MC_VERSION}.jar`);
  const vpath = path.join(work, 'vocabdump.json');
  if (!(o.reuse && fs.existsSync(vpath))) {
    const libs = [];
    const walk = (d) => { for (const e of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, e.name); if (e.isDirectory()) walk(p); else if (e.name.endsWith('.jar')) libs.push(p); } };
    walk(path.join(work, 'libraries'));
    console.error('dump: VocabDump.java');
    execFileSync(findJava(o.java), ['-cp', [serverClasses, ...libs.sort()].join(path.delimiter), path.join(HERE, 'VocabDump.java'), vpath], { cwd: work, stdio: ['ignore', 'ignore', 'inherit'] });
  }
  const vdump = JSON.parse(fs.readFileSync(vpath, 'utf8'));
  const { generate } = await import('./classify.mjs');
  const base = generate(report, dump, fs.readFileSync(path.join(HERE, 'blocks.template.mjs'), 'utf8'), tags);
  const B = await importText(base);
  const pack = S.readDataPack(openZip(serverClasses));
  const e = S.deriveEdges({ report, blocks: B.BLOCKS, pack, vdump, dump, tiers: tables.tiers, modifiers: tables.modifiers, survival: tables.survival });
  return { base, edges: { note: EDGES_NOTE, mc: MC_VERSION, generator: 'kit/tools/gen-vocab.mjs', digests: pack.digests, tagRows: e.tagRows, blocks: e.blocks } };
}

/** Imports a module's text (blocks.mjs has no imports). */
async function importText(text) {
  return import(`data:text/javascript;base64,${Buffer.from(text).toString('base64')}`);
}

/**
 * Every generated file's text from the base blocks.mjs (marker in place), the edges and the tables: {files: {path: text}, report}.
 * The one function both runs call.
 */
export async function generateAll(base, edges, tables) {
  const D = await import('./vocab-derive.mjs');
  const B = await importText(base);
  const K = await import('../lib/kit.mjs');
  // (6c VOC-c) the family groups vocab/1 lists
  const G = await import('../lib/vocab/groups.mjs');
  const r = D.deriveVocab({ blocks: B.BLOCKS, tagBlocks: B.tagBlocks, edges, tables, hand: { STONE_FAMILIES: K.STONE_FAMILIES, WOODS: K.WOODS, woodFamilyOf: K.woodFamilyOf }, emissionOf: B.emissionOf });
  if (!base.includes(MARK)) throw new Error('blocks.mjs base has no vocabulary marker');
  // (6c RS) the free rule's data: the voxel table's natural blocks less survival.json's `free` exceptions
  const voxels = JSON.parse(fs.readFileSync(path.join(ROOT, 'kit', 'voxel_classes.json'), 'utf8')).blocks;
  const freeExcept = D.freeExceptOf(r.fields, voxels, tables.survival.free);
  const files = {
    [OUT.edges]: edgesText(edges),
    [OUT.blocks]: base.replace(`${MARK}\n`, () => `${D.vocabSection(r.fields)}\n`),
    [OUT.survival]: D.survivalModule(r.creativeOnly, r.costs, freeExcept),
    [OUT.survivalRegion]: D.survivalRegionModule(r.fields, voxels, r.creativeOnly, r.costs, freeExcept),
    [OUT.survivalItems]: D.survivalItemsJson(r.creativeOnly, r.costs, tables.survival.mod),
    [OUT.doc]: `${JSON.stringify(D.vocabDoc(r.fields, { groups: G.GROUPS }), null, 1)}\n`,
  };
  return { files, report: { ...r.report, creativeOnly: r.creativeOnly.length + tables.survival.mod.length } };
}

async function main() {
  const { parseArgs, workDir, findLocalJar } = await import('./mcjar.mjs');
  const o = parseArgs(process.argv.slice(2));
  const t0 = Date.now();
  const tables = readTables();
  const probs = tableProblems(tables);
  if (probs.length) {
    console.error(`kit/vocab tables: ${probs.join('; ')}`);
    process.exit(1);
  }
  const work = workDir(o.work);
  const jar = !o['no-jar'] && (findLocalJar('server', o['server-jar'], work) || (o.reuse && fs.existsSync(path.join(work, 'blockdump.json'))));
  let base, edges;
  if (jar) {
    ({ base, edges } = await fromJar({ ...o, work }, tables));
  } else {
    if (!o['no-jar']) console.error('no 26.3 server jar on this machine: deriving from the committed kit/vocab/edges.json (--no-jar)');
    base = stripVocab(fs.readFileSync(OUT.blocks, 'utf8'));
    edges = JSON.parse(fs.readFileSync(OUT.edges, 'utf8'));
  }
  const { files, report } = await generateAll(base, edges, tables);
  const differ = [];
  for (const [f, text] of Object.entries(files)) {
    const cur = fs.existsSync(f) ? fs.readFileSync(f, 'utf8') : null;
    if (cur === text) continue;
    differ.push(path.relative(ROOT, f));
    if (!o.check) {
      fs.mkdirSync(path.dirname(f), { recursive: true });
      fs.writeFileSync(f, text);
    }
  }
  const ms = Date.now() - t0;
  const rep = { mode: jar ? 'jar' : 'no-jar', ms, differ, ...report };
  if (o.report) fs.writeFileSync(o.report, `${JSON.stringify(rep, null, 1)}\n`);
  console.error(`gen-vocab (${rep.mode}, ${ms} ms): ${report.blocks} blocks, ${report.families} families, ${report.creativeOnly} creative-only; ${o.check ? (differ.length ? `DIFFERS: ${differ.join(', ')}` : 'every file up to date') : differ.length ? `wrote ${differ.join(', ')}` : 'nothing to write'}`);
  if (o.check && differ.length) process.exit(1);
}

void os;
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
void pathToFileURL;
