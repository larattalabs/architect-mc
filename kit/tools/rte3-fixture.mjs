#!/usr/bin/env node
// (RTE3) Writes kit/test/fixtures/rte3/layout-ir.json: a districts-style tagged route pass whose numbering skip renumbered an edge's
// pieces (edge d_a__b beside d_a__b_1: b's pieces skip n = 1), each route mixed (ground roads and a stair or graded section over a step
// in the land), for the mod's LayoutsRte3Test (Regions.layout) and kit/test/rte3.test.mjs (which checks the file is current).
//   node kit/tools/rte3-fixture.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { planRegion } from '../lib/region/plan.mjs';
import { makeColumns } from '../lib/region/pack.mjs';
import { region } from '../lib/region/program.mjs';

export const FIXTURE = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'test', 'fixtures', 'rte3', 'layout-ir.json');

/** 96 x 40, ground 64 west of x = 48 and 70 east of it (a step the routes climb). */
function survey() {
  const W = 96, D = 40, c = makeColumns(0, 0, W, D, 1);
  for (let z = 0; z < D; z++) for (let x = 0; x < W; x++) { const i = x + z * W, h = x < 48 ? 64 : 70; c.ground[i] = h; c.height[i] = h; c.floor[i] = 0; c.flags[i] = 0; }
  return c;
}

export async function makeIr() {
  const s = survey();
  const intent = { tagEdges: true, nodes: { a: { at: [8, 65, 8], kind: 'junction' }, b: { at: [88, 71, 8], kind: 'junction' }, a1: { at: [8, 65, 30], kind: 'junction' }, b1: { at: [88, 71, 30], kind: 'junction' } },
    edges: [{ id: 'd_a__b', from: 'a', to: 'b' }, { id: 'd_a__b_1', from: 'a1', to: 'b1' }] };
  const program = { id: 'rte3_layout', passes: ['route'], default: (ctx) => {
    const r = region(ctx);
    r.stages(['ground']);
    r._route(intent);
    r.anchor('entrance', [4, 4]); r.anchor('spawn', [4, 4]);
    return r;
  } };
  const p = await planRegion({ program, programSource: 'x', survey: s, claim: { minX: 0, minZ: 0, maxX: s.width - 1, maxZ: s.depth - 1, minY: -64, maxY: 319 }, seed: '7' });
  if (!p.meta.route.edges.every((e) => e.ok)) throw new Error(`not routed: ${JSON.stringify(p.meta.route.edges.map((e) => [e.id, e.failed]))}`);
  // (the members Layouts reads: the graph, the roads and the paths; parts trimmed to their ids)
  const { graph, roads, paths } = p.ir;
  return { $comment: 'Generated by kit/tools/rte3-fixture.mjs; read by mod LayoutsRte3Test and kit/test/rte3.test.mjs. Do not edit.', graph, roads, paths };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = `${JSON.stringify(await makeIr(), null, 1)}\n`;
  if (process.argv.includes('--check')) {
    const ok = fs.existsSync(FIXTURE) && fs.readFileSync(FIXTURE, 'utf8') === text;
    console.log(ok ? 'current' : 'stale');
    process.exit(ok ? 0 : 1);
  }
  fs.mkdirSync(path.dirname(FIXTURE), { recursive: true });
  fs.writeFileSync(FIXTURE, text);
  console.log(`wrote ${FIXTURE}`);
}
